import { afterEach, describe, expect, test } from "bun:test"
import { mkdir, mkdtemp, readFile, rm } from "fs/promises"
import { setTimeout as sleep } from "node:timers/promises"
import os from "os"
import path from "path"
import { renderPaperExportPipeline, type PaperExportCommandRunner } from "@/paper/export-pipeline"
import { createResearchRun, type ResearchFinalGateState, type ResearchRuntimeOptions } from "@/paper/research/runtime"
import { composeClaimLedger, composeDraftPaper } from "@/paper/research/writing"

const now = "2026-05-10T00:00:00Z"
const created: string[] = []

async function clean(dir: string, attempts = 80): Promise<void> {
  Bun.gc(true)
  await sleep(150)
  return rm(dir, { recursive: true, force: true }).catch((error) => {
    const retryable =
      typeof error === "object" &&
      error !== null &&
      "code" in error &&
      (error.code === "EBUSY" || error.code === "EACCES" || error.code === "EPERM")
    if (!retryable) throw error
    if (attempts <= 1) return
    return clean(dir, attempts - 1)
  })
}

function runtimeOptions(workspace: string, home: string): ResearchRuntimeOptions {
  let index = 0
  return {
    workspace,
    home,
    clock: () => new Date(now),
    idFactory: (kind) => `${kind}-${++index}`,
  }
}

async function newRun() {
  const dir = await mkdtemp(path.join(os.tmpdir(), "paper-fucker-export-pipeline-"))
  created.push(dir)
  const workspace = path.join(dir, "workspace")
  const home = path.join(dir, "home")
  await mkdir(workspace, { recursive: true })
  await mkdir(home, { recursive: true })
  const options = runtimeOptions(workspace, home)
  const handle = await createResearchRun({ topic: "Export pipeline" }, options)
  const ledger = composeClaimLedger({
    topic: "Export pipeline",
    claims: [
      {
        text: "The renderer writes a complete paper bundle.",
        section_id: "results",
        confidence: 0.9,
        source_ids: ["source-renderer"],
        artifact_ids: ["artifact-renderer"],
      },
    ],
    now,
  })
  return {
    ...handle,
    options,
    draft: composeDraftPaper({ title: "Export Pipeline", ledger, now }),
  }
}

const passedGate: ResearchFinalGateState = {
  status: "passed",
  blockers: [],
  updated_at: now,
}

const blockedGate: ResearchFinalGateState = {
  status: "blocked",
  blockers: ["unsupported_claim", "reproduction_failure"],
  updated_at: now,
}

const fakeCommand: PaperExportCommandRunner = async (input) => {
  const outputIndex = input.args.findIndex((arg) => arg === "-o")
  const output = outputIndex >= 0 ? input.args[outputIndex + 1] : undefined
  if (input.tool === "pandoc" && output?.endsWith(".tex")) {
    await Bun.write(output, "\\section{Results}\nGenerated by fake pandoc.\n")
    return { exit_code: 0, stdout: "", stderr: "" }
  }
  if (input.tool === "pandoc" && output?.endsWith(".docx")) {
    await Bun.write(output, new TextEncoder().encode("DOCX generated by fake pandoc"))
    return { exit_code: 0, stdout: "", stderr: "" }
  }
  if (input.tool === "xelatex") {
    const outdir = input.args.find((arg) => arg.startsWith("-output-directory="))?.slice("-output-directory=".length)
    if (!outdir) return { exit_code: 1, stdout: "", stderr: "missing output directory" }
    await Bun.write(path.join(outdir, "bundle-final.pdf"), new TextEncoder().encode("%PDF generated by fake xelatex"))
    return { exit_code: 0, stdout: "", stderr: "" }
  }
  return { exit_code: 1, stdout: "", stderr: `unexpected command ${input.tool} ${input.args.join(" ")}` }
}

afterEach(async () => {
  while (created.length > 0) await clean(created.pop()!)
})

describe("PaperRun export renderer pipeline", () => {
  test("renders final Markdown, LaTeX, PDF, DOCX, and manifest files when gates pass", async () => {
    const run = await newRun()

    const result = await renderPaperExportPipeline(
      run.run_dir,
      {
        mode: "final",
        bundle_id: "bundle-final",
        draft: run.draft,
        final_gate: passedGate,
        source_artifact_ids: ["artifact-renderer"],
        tools: { pandoc: "pandoc", xelatex: "xelatex" },
        command: fakeCommand,
        now,
      },
      run.options,
    )

    expect(result.bundle.status).toBe("final")
    expect(result.bundle.files.map((file) => `${file.format}:${file.status}`)).toEqual([
      "markdown:written",
      "latex:written",
      "pdf:written",
      "docx:written",
    ])
    for (const file of result.bundle.files) {
      expect(await Bun.file(path.join(run.run_dir, file.path)).exists()).toBe(true)
    }
    expect(result.bundle.manifest.path).toBe("exports/bundle-final/manifest.json")
    const manifest = JSON.parse(await readFile(path.join(run.run_dir, result.bundle.manifest.path), "utf8"))
    expect(manifest.status).toBe("final")
    expect(manifest.final_gate_status).toBe("passed")
    expect(manifest.files).toHaveLength(4)
  })

  test("returns actionable diagnostics when pandoc or a LaTeX engine is missing", async () => {
    const run = await newRun()

    const result = await renderPaperExportPipeline(
      run.run_dir,
      {
        mode: "final",
        bundle_id: "bundle-missing-tools",
        draft: run.draft,
        final_gate: passedGate,
        source_artifact_ids: [],
        tools: {},
        now,
      },
      run.options,
    )

    expect(result.bundle.files.find((file) => file.format === "markdown")?.status).toBe("written")
    expect(result.bundle.manifest.tool_diagnostics.join("\n")).toContain("pandoc")
    expect(result.bundle.manifest.tool_diagnostics.join("\n")).toContain("LaTeX")
    expect(result.bundle.files.filter((file) => file.status === "failed").map((file) => file.format)).toContain("pdf")
  })

  test("falls back to the next LaTeX engine when latexmk fails", async () => {
    const run = await newRun()
    const calls: Array<{ tool: string; args: string[] }> = []
    const command: PaperExportCommandRunner = async (input) => {
      calls.push({ tool: input.tool, args: input.args })
      const outputIndex = input.args.findIndex((arg) => arg === "-o")
      const output = outputIndex >= 0 ? input.args[outputIndex + 1] : undefined
      if (input.tool === "pandoc" && output?.endsWith(".tex")) {
        await Bun.write(output, "\\section{Results}\nGenerated by fake pandoc.\n")
        return { exit_code: 0, stdout: "", stderr: "" }
      }
      if (input.tool === "pandoc" && output?.endsWith(".docx")) {
        await Bun.write(output, new TextEncoder().encode("DOCX generated by fake pandoc"))
        return { exit_code: 0, stdout: "", stderr: "" }
      }
      if (input.tool === "latexmk") return { exit_code: 1, stdout: "", stderr: "latexmk runscript.tlu failure" }
      if (input.tool === "xelatex") {
        const outdir = input.args.find((arg) => arg.startsWith("-output-directory="))?.slice("-output-directory=".length)
        if (!outdir) return { exit_code: 1, stdout: "", stderr: "missing output directory" }
        await Bun.write(path.join(outdir, "bundle-fallback.pdf"), new TextEncoder().encode("%PDF generated by fallback xelatex"))
        return { exit_code: 0, stdout: "", stderr: "" }
      }
      return { exit_code: 1, stdout: "", stderr: `unexpected command ${input.tool}` }
    }

    const result = await renderPaperExportPipeline(
      run.run_dir,
      {
        mode: "final",
        bundle_id: "bundle-fallback",
        draft: run.draft,
        final_gate: passedGate,
        source_artifact_ids: [],
        tools: { pandoc: "pandoc", latexmk: "latexmk", xelatex: "xelatex" },
        command,
        now,
      },
      run.options,
    )

    const pdf = result.bundle.files.find((file) => file.format === "pdf")
    expect(calls.map((call) => call.tool)).toContain("latexmk")
    expect(calls.map((call) => call.tool)).toContain("xelatex")
    expect(calls.find((call) => call.tool === "xelatex")?.args.join("\n")).not.toContain("\\")
    expect(pdf?.status).toBe("written")
    expect(pdf?.diagnostics.join("\n")).toContain("latexmk failed")
    expect(await Bun.file(path.join(run.run_dir, pdf!.path)).exists()).toBe(true)
  })

  test("visibly marks forced draft exports with failed checks", async () => {
    const run = await newRun()

    const result = await renderPaperExportPipeline(
      run.run_dir,
      {
        mode: "forced_draft",
        bundle_id: "bundle-forced",
        draft: run.draft,
        final_gate: blockedGate,
        source_artifact_ids: [],
        tools: { pandoc: "pandoc", xelatex: "xelatex" },
        command: fakeCommand,
        now,
      },
      run.options,
    )

    const markdown = result.bundle.files.find((file) => file.format === "markdown")
    expect(markdown?.status).toBe("written")
    expect(await readFile(path.join(run.run_dir, markdown!.path), "utf8")).toContain("FORCED DRAFT")
    const manifest = JSON.parse(await readFile(path.join(run.run_dir, result.bundle.manifest.path), "utf8"))
    expect(manifest.forced).toBe(true)
    expect(manifest.failed_checks).toEqual(["unsupported_claim", "reproduction_failure"])
  })
})
